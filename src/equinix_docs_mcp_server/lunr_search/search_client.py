"""Search docs.equinix.com's prebuilt lunr index.

docs.equinix.com publishes /search-index.json, generated by
docusaurus-search-local: a JSON array of serialized lunr.js 2.x indexes, one
per document type, each paired with its documents in short form
(``i`` id, ``t`` text, ``u`` page path, ``h`` anchor, ``s`` section title,
``p`` parent page id, ``b`` breadcrumb).

The indexed terms are stemmed (``connection`` is stored as ``connect``), so
queries must go through the same pipeline. lunr.py loads the serialized
indexes as-is and applies the index's own search pipeline, giving the same
matching and BM25 scoring as the site's search box.
"""

import json
import re
from dataclasses import dataclass
from typing import Any, Dict, List, Optional

from lunr.exceptions import BaseLunrException
from lunr.index import Index

# docusaurus-search-local's SearchDocumentType order, and how much a hit in
# each counts towards its page's score.
_TYPE_WEIGHTS = {
    0: 2.0,  # page titles
    1: 1.5,  # headings
    2: 1.2,  # descriptions
    3: 1.2,  # keywords
    4: 1.0,  # content
}

# Words, keeping inner dots (2.0, ipv4.x). Everything else, including
# lunr's query syntax (field:, boost^, fuzzy~, +required, -prohibited,
# wild*card) and quotes, is a separator, so free text never fails to parse.
# The index pipeline only stems, with no trimmer, so stray punctuation left
# on a term would stop it matching.
_WORD = re.compile(r"\w(?:[\w.]*\w)?")

# Index types describing a whole page rather than a section within it.
_PAGE_LEVEL_TYPES = {0, 2, 3}

# A page ranks by its best hit in each index type; after the strongest
# type, the others add this fraction of their best hit. Summing every hit
# instead lets long pages (release notes) win on volume alone.
_SECONDARY_WEIGHT = 0.3


def query_text(query: str) -> str:
    """Free text as a lunr query that always parses (see _WORD)."""
    return " ".join(_WORD.findall(query))


@dataclass
class _Indexed:
    weight: float
    index: Index
    documents: Dict[str, Dict[str, Any]]


class Client:
    """Query every index in a docusaurus-search-local search-index.json."""

    def __init__(self, path: str):
        self.path = path
        self._indexes: List[_Indexed] = []
        self._titles: Dict[str, str] = {}

    def load(self) -> None:
        with open(self.path, "r", encoding="utf8") as fh:
            payload = json.load(fh)

        self._indexes = []
        self._titles = {}
        for position, item in enumerate(payload):
            serialized = item.get("index")
            if not serialized:
                continue
            documents = {str(d.get("i")): d for d in item.get("documents", [])}
            self._indexes.append(
                _Indexed(
                    weight=_TYPE_WEIGHTS.get(position, 1.0),
                    index=Index.load(serialized),
                    documents=documents,
                )
            )
            if position == 0:
                self._titles = {
                    d["u"]: d["t"]
                    for d in documents.values()
                    if d.get("u") and d.get("t")
                }

    def search(self, query: str, limit: int = 8) -> List[Dict[str, Any]]:
        """Return up to ``limit`` pages, best first.

        Terms are OR-ed and ranked by lunr, as on the site. Hits are grouped
        by page (see _SECONDARY_WEIGHT), and each result points at the
        highest-scoring section within its page.
        """
        text = query_text(query)
        if not text:
            return []

        pages: Dict[str, Dict[str, Any]] = {}
        for type_id, indexed in enumerate(self._indexes):
            try:
                hits = indexed.index.search(text)
            except BaseLunrException:
                continue
            for hit in hits:
                doc = indexed.documents.get(str(hit["ref"]))
                if not doc or not doc.get("u"):
                    continue
                score = hit["score"] * indexed.weight
                page = pages.setdefault(
                    doc["u"], {"url": doc["u"], "by_type": {}, "best": None}
                )
                by_type = page["by_type"]
                by_type[type_id] = max(by_type.get(type_id, 0.0), score)
                if doc.get("h") and (page["best"] is None or score > page["best"][0]):
                    page["best"] = (score, doc)

        for page in pages.values():
            best_per_type = sorted(page["by_type"].values(), reverse=True)
            page["score"] = best_per_type[0] + _SECONDARY_WEIGHT * sum(
                best_per_type[1:]
            )

        ranked = sorted(pages.values(), key=lambda p: p["score"], reverse=True)
        results = []
        for page in ranked[:limit]:
            results.append(self._result(page))
        return results

    def _result(self, page: Dict[str, Any]) -> Dict[str, Any]:
        url = page["url"]
        section: Optional[str] = None
        anchor = ""
        best = page["best"]
        # Point at a section only when it matched at least as well as the
        # page itself did on its title, description or keywords.
        page_level = max(
            (v for t, v in page["by_type"].items() if t in _PAGE_LEVEL_TYPES),
            default=0.0,
        )
        if best is not None and best[0] >= page_level:
            doc = best[1]
            anchor = doc.get("h", "")
            # Content hits carry their heading in "s"; heading hits are the
            # heading text itself.
            section = doc.get("s") or doc.get("t")

        title = self._titles.get(url, url)

        return {
            "title": title,
            "url": url,
            "section": section if section != title else None,
            "anchor": anchor,
            "score": page["score"],
        }
